/**
 * SRS 벽 킥 [회전 전 상태][방향 0 = CW, 1 = CCW] → 시도 오프셋 [dx0, dy0, ..., dx4, dy4]
 * SRS 표(y 위쪽 증가)의 dy 부호를 뒤집어 y 아래쪽 증가 좌표로 옮긴 값
 */
const JLSTZ_KICKS: readonly (readonly (readonly number[])[])[] = [
  [
    [0, 0, -1, 0, -1, -1, 0, 2, -1, 2], // 0 → R
    [0, 0, 1, 0, 1, -1, 0, 2, 1, 2], // 0 → L
  ],
  [
    [0, 0, 1, 0, 1, 1, 0, -2, 1, -2], // R → 2
    [0, 0, 1, 0, 1, 1, 0, -2, 1, -2], // R → 0
  ],
  [
    [0, 0, 1, 0, 1, -1, 0, 2, 1, 2], // 2 → L
    [0, 0, -1, 0, -1, -1, 0, 2, -1, 2], // 2 → R
  ],
  [
    [0, 0, -1, 0, -1, 1, 0, -2, -1, -2], // L → 0
    [0, 0, -1, 0, -1, 1, 0, -2, -1, -2], // L → 2
  ],
];

const I_KICKS: readonly (readonly (readonly number[])[])[] = [
  [
    [0, 0, -2, 0, 1, 0, -2, 1, 1, -2], // 0 → R
    [0, 0, -1, 0, 2, 0, -1, -2, 2, 1], // 0 → L
  ],
  [
    [0, 0, -1, 0, 2, 0, -1, -2, 2, 1], // R → 2
    [0, 0, 2, 0, -1, 0, 2, -1, -1, 2], // R → 0
  ],
  [
    [0, 0, 2, 0, -1, 0, 2, -1, -1, 2], // 2 → L
    [0, 0, 1, 0, -2, 0, 1, 2, -2, -1], // 2 → R
  ],
  [
    [0, 0, 1, 0, -2, 0, 1, 2, -2, -1], // L → 0
    [0, 0, -2, 0, 1, 0, -2, 1, 1, -2], // L → 2
  ],
];

export function getKicks(piece: number, fromRotation: number, clockwise: boolean): readonly number[] {
  const table = piece === PIECE.I ? I_KICKS : JLSTZ_KICKS;
  return table[fromRotation][clockwise ? 0 : 1];
}

